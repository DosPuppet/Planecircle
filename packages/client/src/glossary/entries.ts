/**
 * Glossary: keyword abilities, keyword actions, ability words, tokens and counters, game terms. Each entry has its
 * English name and definition (`msg`: their French is in the catalogs) and, for the words highlighted in a rules text,
 * the forms that find it there (`en`, `fr`: regular expressions, case-insensitive, matched between word boundaries; a
 * French text without a French printing is in English, so French texts are searched with both).
 *
 * A name already used elsewhere with another French wording (a mode label "Investigate", in the imperative) has the
 * `ctx:glossary|` prefix: its French there is the name of the mechanic.
 *
 * Order matters: at a given position the first entry that matches wins, so a longer form ("double strike", "manifest
 * dread") comes before the entry it contains. `glossary.test.ts` checks that every form finds at least one card text
 * of the catalog in its language.
 */
import type { Keyword } from "@mtgx/engine";
import { msg } from "@mtgx/engine";

export type GlossaryKind = "ability" | "action" | "abilityWord" | "object" | "term";

export interface GlossaryEntry {
  id: string;
  kind: GlossaryKind;
  /** English name (`msg`). */
  name: string;
  /** Definition (`msg`). */
  help: string;
  /** Forms in an English rules text (regular expression source); none: in the glossary only. */
  en?: string;
  /** Forms in a French rules text; none: the English forms (the same word in both languages). */
  fr?: string;
  /** Engine keyword whose badge on a permanent shows this definition. */
  keyword?: Keyword;
}

