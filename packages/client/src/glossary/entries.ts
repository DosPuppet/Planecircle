const BY_KEYWORD = new Map(GLOSSARY.flatMap((e) => (e.keyword ? [[e.keyword, e] as const] : [])));

/** The entry that explains an engine keyword (badges on the battlefield). */
export function glossaryForKeyword(k: Keyword): GlossaryEntry | undefined {
  return BY_KEYWORD.get(k);
}
